// In TypeScript, we can explicitly define the type of a variable for better type safety
// It's not always necessary to define the type explicitly, because TypeScript can infer the type of a variable
// Type inference is a feature where TypeScript automatically detects the variable's type based on its value

// However, sometimes TypeScript cannot infer the type correctly, especially for complex or ambiguous values.
// In such cases, we must explicitly define the type to ensure correct behavior.


let a: number = 1;
let b: string = "afnkjnf"
console.log(a);
console.log(b);